def test_huggingface_gradient(model: Qwen3LM, params: Parameters, reference: dict[str, jax.Array]) -> None:
    def loss(weights: Parameters) -> jax.Array:
        output = model.apply({"params": weights}, reference["tokens"], position_ids=reference["positions"])
        return jnp.square(output.logits).mean()  # ()

    gradient = jax.jit(jax.grad(loss))(params)
    assert jax.tree.map(jnp.shape, gradient) == jax.tree.map(jnp.shape, params)
    np.testing.assert_allclose(gradient["model.embed_tokens.weight"], reference["embedding_grad"], atol=2e-6, rtol=2e-5)
    state = TrainState.create(apply_fn=model.apply, params=params, tx=optax.sgd(0.01))
    updated = state.apply_gradients(grads=gradient)
    assert int(updated.step) == 1
    evaluate_loss = jax.jit(loss)
    assert float(evaluate_loss(updated.params)) < float(evaluate_loss(state.params))


@pytest.mark.parametrize("dtype", ["float32", "bfloat16"])
def test_gradient_checkpointing(model: Qwen3LM, params: Parameters, dtype: str) -> None:
    assert model.gradient_checkpointing
    assert model.scan_layers
    model = model.clone(dtype=dtype)
    plain = model.clone(gradient_checkpointing=False, scan_layers=False)
    tokens = jnp.array([[0, 0, 0], [0, 1, 4]], jnp.int32)  # (B=2, T=3)
    mask = jnp.array([[False, False, False], [False, True, True]])  # (B, T)

    def loss(weights: Parameters, lm: Qwen3LM) -> tuple[jax.Array, jax.Array]:
        logits = lm.apply({"params": weights}, tokens, attention_mask=mask).logits  # (B, T, V=13)
        return jnp.square(logits).mean(), logits  # (), (B, T, V)

    evaluate = jax.jit(jax.value_and_grad(loss, has_aux=True), static_argnums=1)
    (expected_loss, expected), expected_grad = evaluate(params, plain)  # (), (B, T, V), parameter shapes.
    tolerance = 0.02 if dtype == "bfloat16" else 2e-6
    trace = jax.make_jaxpr(loss, static_argnums=1)
    # Check scan/rematerialization independently and together against the unrolled baseline.
    for lm in (model, model.clone(gradient_checkpointing=False), model.clone(scan_layers=False), plain):
        if lm != plain:
            (actual_loss, actual), actual_grad = evaluate(params, lm)  # (), (B, T, V), parameter shapes.
            assert actual.shape == expected.shape == (2, 3, 13)
            np.testing.assert_allclose(actual, expected, atol=tolerance, rtol=tolerance)
            np.testing.assert_allclose(actual_loss, expected_loss, atol=tolerance, rtol=tolerance)
            assert jax.tree.map(jnp.shape, actual_grad) == model.config.parameter_shapes()
            for name in params:
                np.testing.assert_allclose(actual_grad[name], expected_grad[name], atol=tolerance, rtol=tolerance)

        equations = trace(params, lm).jaxpr.eqns
        scans = [eqn for eqn in equations if eqn.primitive.name == "scan"]
        assert len(scans) == int(lm.scan_layers)
        if lm.scan_layers:
            assert scans[0].params["length"] == model.config.num_hidden_layers
            equations = scans[0].params["jaxpr"].jaxpr.eqns
        count = (1 if lm.scan_layers else model.config.num_hidden_layers) if lm.gradient_checkpointing else 0
        assert sum(eqn.primitive.name == "remat2" for eqn in equations) == count


def test_bfloat16_silu_opmath() -> None:
    # Real first-layer activation; CUDA PyTorch 2.9.1 SiLU and its sum gradient.
    inputs = jnp.array([[0.40625]], jnp.bfloat16)  # (B=1, D=1).

    def loss(x: jax.Array) -> tuple[jax.Array, jax.Array]:  # (B, D).
        output = _silu(x)  # (B, D).
        return output.astype(jnp.float32).sum(), output  # (), (B, D).

    (_, output), gradient = jax.jit(jax.value_and_grad(loss, has_aux=True))(inputs)
    assert output.shape == gradient.shape == inputs.shape
    assert output.dtype == gradient.dtype == jnp.bfloat16
    np.testing.assert_array_equal(output, [[0.244140625]])
    np.testing.assert_array_equal(gradient, [[0.69921875]])


def test_bfloat16_residual_normalization() -> None:
    x = jnp.array([[1, 2, 3, 4]], jnp.bfloat16)  # (B=1, D=4)
    residual = jnp.array([[0.00390625, -0.0078125, 0.0078125, -0.015625]], jnp.bfloat16)  # (B, D)
    weight = jnp.array([0.8, 0.9, 1.1, 1.2], jnp.bfloat16)  # (D,)
    normalized, stored = jax.jit(_add_rms_norm)(x, residual, weight, 1e-6)  # Each (B, D).
    assert normalized.shape == stored.shape == (1, 4)
    assert normalized.dtype == stored.dtype == jnp.bfloat16
    # vLLM 0.27 compiled native fused_add_rms_norm: normalize before rounding the sum.
    np.testing.assert_array_equal(normalized, [[0.294921875, 0.65625, 1.2109375, 1.75]])
    np.testing.assert_array_equal(stored, [[1.0, 1.9921875, 3.0, 3.984375]])


def test_bfloat16_projection_accumulates_in_float32() -> None:
    if jax.default_backend() != "gpu":
        pytest.skip("Regression for shape-dependent CUDA GEMM selection")
    row = jax.random.normal(jax.random.key(1), (2048,)).astype(jnp.bfloat16)  # (I,)
    weight = (0.01 * jax.random.normal(jax.random.key(2), (1024, 2048))).astype(jnp.bfloat16)  # (O, I)
    # This row count selects a less accurate cuBLAS algorithm with Precision.HIGHEST.
    inputs = jnp.tile(row, (4021, 1))  # (M, I)
    expected = jnp.matmul(
        row.astype(jnp.float32), weight.astype(jnp.float32).T, precision=jax.lax.Precision.HIGHEST
    ).astype(jnp.bfloat16)  # (O,)
    actual = jax.jit(_linear, static_argnames="dtype")(inputs, weight, "bfloat16")  # (M, O)
    assert actual.shape == (4021, 1024)
    assert actual.dtype == jnp.bfloat16
    # Allow rare FP32 reduction-order rounding ties, not BF16 partial-sum errors.
    error = jnp.abs(actual[0].astype(jnp.float32) - expected.astype(jnp.float32))  # (O,)
    assert float(error.mean()) < 1e-5
    assert float(jnp.mean(error != 0)) < 0.005
    np.testing.assert_array_equal(actual[0], actual[-1])


def test_bfloat16_projection_preserves_float32_output_gradients() -> None:
    inputs = jnp.array([[0.25, 0.5]], jnp.float32)  # (B=1, I=2)
    weight = jnp.array([[1.0, 2.0], [1.0, 2.0]], jnp.float32)  # (O=2, I)
    cotangent = jnp.array([[0.200001, -0.2]], jnp.float32)  # (B, O)

    def loss(values: jax.Array) -> tuple[jax.Array, jax.Array]:  # (B, I) -> (), (B, O)
        output = _linear(values, weight, "bfloat16", output_dtype=jnp.float32)  # (B, O)
        return jnp.sum(output * cotangent), output  # (), (B, O)

    (_, output), gradient = jax.jit(jax.value_and_grad(loss, has_aux=True))(inputs)  # (), (B, O), (B, I)
    assert output.shape == gradient.shape == (1, 2)
    assert output.dtype == gradient.dtype == jnp.float32
    expected = (cotangent @ weight).astype(jnp.bfloat16).astype(jnp.float32)  # (B, I)
    # Truncating the FP32 head cotangent to BF16 would cancel this gradient to zero.
    np.testing.assert_array_equal(gradient, expected)


def test_bfloat16_master_weights_match_published_weights(model: Qwen3LM, params: Parameters) -> None:
    model = model.clone(dtype="bfloat16")
    master = {
        name: weight * jnp.linspace(0.803, 1.207, weight.shape[-1]) if "norm" in name else weight
        for name, weight in params.items()
    }  # HF parameter shapes; norm scales are deliberately between BF16 values.
    published = jax.tree.map(lambda value: value.astype(jnp.bfloat16).astype(jnp.float32), master)
    tokens = jnp.array([[1, 4, 2], [0, 1, 4]], jnp.int32)  # (B=2, T=3)

    def loss(weights: Parameters) -> tuple[jax.Array, jax.Array]:
        logits = model.apply({"params": weights}, tokens).logits  # (B, T, V=13)
        return jnp.square(logits).mean(), logits  # (), (B, T, V)

    evaluate = jax.jit(jax.value_and_grad(loss, has_aux=True))
    (_, actual), actual_grad = evaluate(master)  # (B, T, V), HF parameter shapes.
    (_, expected), expected_grad = evaluate(published)  # (B, T, V), HF parameter shapes.
    assert actual.shape == expected.shape == (2, 3, 13)
    np.testing.assert_array_equal(actual, expected)
    assert jax.tree.map(jnp.shape, actual_grad) == model.config.parameter_shapes()
    for name in master:
        np.testing.assert_array_equal(actual_grad[name], expected_grad[name])


def test_bfloat16_logits_retain_float32_accumulation(model: Qwen3LM, params: Parameters) -> None:
    model = model.clone(dtype="bfloat16")
    # Zero branches leave the embeddings as the residual through every decoder layer.
    params = {
        name: value if "norm" in name or "embed_tokens" in name else jnp.zeros_like(value)
        for name, value in params.items()
    }  # HF parameter shapes.
    tokens = jnp.array([[1, 4, 2], [0, 1, 4]], jnp.int32)  # (B=2, T=3)
    embedding = params["model.embed_tokens.weight"].astype(jnp.bfloat16)  # (V=13, D=8)
    hidden = jax.jit(_rms_norm)(embedding[tokens], params["model.norm.weight"], model.config.rms_norm_eps)  # (B, T, D)
    expected = jnp.matmul(
        hidden.astype(jnp.float32), embedding.astype(jnp.float32).T, precision=jax.lax.Precision.HIGHEST
    )  # (B, T, V)
    actual = jax.jit(model.apply)({"params": params}, tokens).logits  # (B, T, V)
    assert actual.shape == (2, 3, 13)
    assert actual.dtype == jnp.float32
    np.testing.assert_allclose(actual, expected, atol=1e-7, rtol=1e-6)
    assert not np.array_equal(actual, expected.astype(jnp.bfloat16).astype(jnp.float32))


